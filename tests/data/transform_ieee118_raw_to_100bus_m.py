def split_sections(raw_path):
    with open(raw_path) as fh:
        all_lines = [line.rstrip() for line in fh]
    sections = {'HEADER': all_lines[:3]}
    current_name = 'BUS'
    current_lines = []
    for line in all_lines[3:]:
        if line.strip() == 'Q':
            break
        if re.match(r'^\s*0\s*/', line):
            sections[current_name] = current_lines
            next_match = re.search(r'BEGIN\s+(.+?)\s+DATA', line, re.IGNORECASE)
            current_name = next_match.group(1).upper() if next_match else '__END__'
            current_lines = []
        elif line.strip():
            current_lines.append(line)
    return sections


def _fields(line):
    return [x.strip().strip("'") for x in line.split(',')]


def _parse_baseMVA(header_lines):
    return float(_fields(header_lines[0])[1])


def _parse_bus(lines):
    rows = []
    for line in lines:
        f = _fields(line)
        rows.append({
            'bus_i':  int(f[0]),
            'type':   int(f[3]),
            'Pd':     0.0,
            'Qd':     0.0,
            'Gs':     0.0,
            'Bs':     0.0,
            'area':   int(f[4]),
            'Vm':     float(f[7]),
            'Va':     float(f[8]),
            'baseKV': float(f[2]),
            'zone':   int(f[5]),
            'Vmax':   1.1,
            'Vmin':   0.9,
        })
    return pd.DataFrame(rows).set_index('bus_i')


def _parse_load(lines):
    rows = []
    for line in lines:
        f = _fields(line)
        if int(f[2]) == 1:
            rows.append({'bus_i': int(f[0]), 'PL': float(f[5]), 'QL': float(f[6])})
    if not rows:
        return pd.DataFrame(columns=['PL', 'QL'])
    return pd.DataFrame(rows).groupby('bus_i')[['PL', 'QL']].sum()


def _parse_fixed_shunt(lines):
    rows = []
    for line in lines:
        f = _fields(line)
        if int(f[2]) == 1:
            rows.append({'bus_i': int(f[0]), 'GL': float(f[3]), 'BL': float(f[4])})
    if not rows:
        return pd.DataFrame(columns=['GL', 'BL'])
    return pd.DataFrame(rows).groupby('bus_i')[['GL', 'BL']].sum()


def _parse_generator(lines):
    rows = []
    for line in lines:
        f = _fields(line)
        rows.append({
            'bus':    int(f[0]),
            'Pg':     float(f[2]),
            'Qg':     float(f[3]),
            'Qmax':   float(f[4]),
            'Qmin':   float(f[5]),
            'Vg':     float(f[6]),
            'mBase':  float(f[8]),
            'status': int(f[14]),
            'Pmax':   float(f[16]),
            'Pmin':   float(f[17]),
        })
    return pd.DataFrame(rows)


def _parse_branch(lines):
    rows = []
    for line in lines:
        f = _fields(line)
        rows.append({
            'fbus':   int(f[0]),
            'tbus':   int(f[1]),
            'r':      float(f[3]),
            'x':      float(f[4]),
            'b':      float(f[5]),
            'rateA':  float(f[6]),
            'rateB':  float(f[7]),
            'rateC':  float(f[8]),
            'ratio':  0.0,
            'angle':  0.0,
            'status': int(f[13]),
            'angmin': -360.0,
            'angmax':  360.0,
        })
    return pd.DataFrame(rows)


def _parse_transformer(lines):
    rows = []
    i = 0
    while i + 3 < len(lines):
        r1 = _fields(lines[i])
        r2 = _fields(lines[i + 1])
        r3 = _fields(lines[i + 2])
        if int(r1[2]) != 0:
            i += 4
            continue
        rows.append({
            'fbus':   int(r1[0]),
            'tbus':   int(r1[1]),
            'r':      float(r2[0]),
            'x':      float(r2[1]),
            'b':      0.0,
            'rateA':  float(r3[3]),
            'rateB':  float(r3[4]),
            'rateC':  float(r3[5]),
            'ratio':  float(r3[0]),
            'angle':  float(r3[2]),
            'status': int(r1[11]),
            'angmin': -360.0,
            'angmax':  360.0,
        })
        i += 4
    return pd.DataFrame(rows)


def build_mpc(sections):
    baseMVA  = _parse_baseMVA(sections['HEADER'])
    bus_df   = _parse_bus(sections.get('BUS', []))
    load_df  = _parse_load(sections.get('LOAD', []))
    shunt_df = _parse_fixed_shunt(sections.get('FIXED SHUNT', []))
    gen_df   = _parse_generator(sections.get('GENERATOR', []))
    br_df    = _parse_branch(sections.get('BRANCH', []))
    xfmr_df  = _parse_transformer(sections.get('TRANSFORMER', []))
    if not load_df.empty:
        bus_df.loc[load_df.index, 'Pd'] += load_df['PL']
        bus_df.loc[load_df.index, 'Qd'] += load_df['QL']
    if not shunt_df.empty:
        bus_df.loc[shunt_df.index, 'Gs'] += shunt_df['GL']
        bus_df.loc[shunt_df.index, 'Bs'] += shunt_df['BL']
    branch_df = pd.concat([br_df, xfmr_df], ignore_index=True)
    return baseMVA, bus_df.reset_index(), gen_df, branch_df


_BUS_COLS    = ['bus_i','type','Pd','Qd','Gs','Bs','area','Vm','Va','baseKV','zone','Vmax','Vmin']
_GEN_COLS    = ['bus','Pg','Qg','Qmax','Qmin','Vg','mBase','status','Pmax','Pmin']
_BRANCH_COLS = ['fbus','tbus','r','x','b','rateA','rateB','rateC','ratio','angle','status','angmin','angmax']


def _fmt(v):
    fv = float(v)
    if fv == int(fv) and abs(fv) < 1e9:
        return str(int(fv))
    return f'{fv:.6g}'


def _write_matrix(fh, name, df, cols):
    fh.write(f'%% {name} data\n')
    fh.write(f'mpc.{name} = [\n')
    for _, row in df[cols].iterrows():
        fh.write('\t' + '\t'.join(_fmt(row[c]) for c in cols) + '\n')
    fh.write('];\n\n')


def _gencost_coeffs(gen_df, c_quad=0.01, c_lin=20.0, c_const=100.0, noise=0.15, seed=None):
    """
    Return (a, b, c) quadratic cost coefficients for each generator.
    Larger units (higher Pmax) get lower costs: a and b scale as pmax_ref/Pmax.
    A multiplicative noise in [1-noise, 1+noise] is then applied independently
    to a, b, and c so all units have slightly different costs.
    Cost function: f(P) = a*P^2 + b*P + c
    """
    _EPS = 1e-4  # hard floor — coefficients must never be zero
    rng = random.Random(seed)
    pmax_ref = gen_df['Pmax'].median()
    coeffs = []
    for pmax in gen_df['Pmax']:
        scale = pmax_ref / pmax if pmax > 0 else 1.0
        a = max(_EPS, c_quad * scale * (1.0 + rng.uniform(-noise, noise)))
        b = max(_EPS, c_lin  * scale * (1.0 + rng.uniform(-noise, noise)))
        c = max(_EPS, c_const        * (1.0 + rng.uniform(-noise, noise)))
        coeffs.append((a, b, c))
    return coeffs


def write_m(path, func_name, baseMVA, bus_df, gen_df, branch_df, seed=None):
    with open(path, 'w') as fh:
        fh.write(f'function mpc = {func_name}\n')
        fh.write("mpc.version = '2';\n")
        fh.write(f'mpc.baseMVA = {baseMVA:.2f};\n\n')
        _write_matrix(fh, 'bus', bus_df, _BUS_COLS)
        _write_matrix(fh, 'gen', gen_df, _GEN_COLS)
        fh.write('%% generator cost data\n')
        fh.write('%\t1\tstartup\tshutdown\tn\tx1\ty1\t...\txn\tyn\n')
        fh.write('%\t2\tstartup\tshutdown\tn\tc(n-1)\t...\tc0\n')
        fh.write('mpc.gencost = [\n')
        for a, b, c in _gencost_coeffs(gen_df, seed=seed):
            fh.write(f'\t2\t0\t0\t3\t{a:.6g}\t{b:.6g}\t{c:.6g}\n')
        fh.write('];\n\n')
        _write_matrix(fh, 'branch', branch_df, _BRANCH_COLS)


