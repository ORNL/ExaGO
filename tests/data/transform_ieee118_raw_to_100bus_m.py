# ── key functions (must match how diff keys were generated) ──────────────────

def key_bus(line):
    return int(line.split(",")[0].strip())

def key_load(line):
    p = line.split(",")
    return (int(p[0].strip()), p[1].strip().strip("'"))

def key_shunt(line):
    p = line.split(",")
    return (int(p[0].strip()), p[1].strip().strip("'"))

def key_gen(line):
    p = line.split(",")
    return (int(p[0].strip()), p[1].strip().strip("'"))

def key_branch(line):
    p = line.split(",")
    return (int(p[0].strip()), int(p[1].strip()), p[2].strip().strip("'"))

def key_xfmr(line):
    p = line.split(",")
    return (int(p[0].strip()), int(p[1].strip()),
            int(p[2].strip()), p[3].strip().strip("'"))


# ── section transformers ─────────────────────────────────────────────────────

def apply_simple(v1_lines, diff_dict, key_fn):
    """
    Walk v1 lines; replace/remove per diff_dict; append added entries at end.
    Works for buses, loads, fixed_shunts, generators.
    """
    output = []
    for line in v1_lines:
        key = key_fn(line.strip())
        if key in diff_dict:
            entry = diff_dict[key]
            if entry["after"] is not None:
                output.append(entry["after"])   # replace
            # else after=None → removed in v9, skip
        else:
            output.append(line.strip())         # unchanged

    # Added entries (before=None)
    for key, entry in diff_dict.items():
        if entry["before"] is None:
            output.append(entry["after"])

    return output


def apply_branches(v1_lines, diff_dict):
    """
    Branch handling with duplicate support.

    v1 has pairs of identical (from, to, '1 ') lines for some corridors.
    In v9 these become circuit '1 ' + circuit '2 '.
    The second occurrence of a duplicate is mapped to the '2 ' circuit entry
    in diff (which has before=None).
    """
    output = []
    seen_count    = {}   # key → occurrence count so far
    consumed_adds = set()  # '2 ' keys already emitted from duplicate handling

    for line in v1_lines:
        key = key_branch(line.strip())
        seen_count[key] = seen_count.get(key, 0) + 1
        n = seen_count[key]

        if n == 1:
            # Normal / first occurrence
            if key in diff_dict:
                entry = diff_dict[key]
                if entry["after"] is not None:
                    output.append(entry["after"])   # replace
                # else: removed in v9, skip
            else:
                output.append(line.strip())         # unchanged

        else:
            # Duplicate: second (or later) occurrence maps to circuit 'n '
            alt_key = (key[0], key[1], str(n) + " ")
            if alt_key in diff_dict and diff_dict[alt_key]["before"] is None:
                output.append(diff_dict[alt_key]["after"])
                consumed_adds.add(alt_key)
            # else: duplicate was dropped entirely in v9, skip

    # Append brand-new branches (before=None, not consumed by duplicate logic)
    for key, entry in diff_dict.items():
        if entry["before"] is None and key not in consumed_adds:
            output.append(entry["after"])

    return output


def apply_xfmrs(v1_blocks, diff_dict):
    """
    Same logic as apply_simple but each record is a list of 4 strings.
    """
    output_blocks = []

    for block in v1_blocks:
        key = key_xfmr(block[0].strip())
        if key in diff_dict:
            entry = diff_dict[key]
            if entry["after"] is not None:
                output_blocks.append(entry["after"])    # replace all 4 lines
            # else: removed, skip
        else:
            output_blocks.append([l.strip() for l in block])   # unchanged

    # Append added transformers
    for key, entry in diff_dict.items():
        if entry["before"] is None:
            output_blocks.append(entry["after"])

    return output_blocks


# ── main transform ───────────────────────────────────────────────────────────

def transform(input_path, output_path, verbose=True):
    header, sections = parse_raw_file(input_path)

    out_buses    = apply_simple(sections["bus"],         buses,        key_bus)
    out_loads    = apply_simple(sections["load"],        loads,        key_load)
    out_shunts   = apply_simple(sections["shunt"],       fixed_shunts, key_shunt)
    out_gens     = apply_simple(sections["gen"],         generators,   key_gen)
    out_branches = apply_branches(sections["branch"],    branches)
    out_xfmrs    = apply_xfmrs(sections["xfmr_blocks"], transformers)

    seps = sections["separators"]
    with open(output_path, "w") as fh:
        fh.writelines(header)

        for ln in out_buses:    fh.write(_nl(ln))
        fh.write(_nl(seps[0]))

        for ln in out_loads:    fh.write(_nl(ln))
        fh.write(_nl(seps[1]))

        for ln in out_shunts:   fh.write(_nl(ln))
        fh.write(_nl(seps[2]))

        for ln in out_gens:     fh.write(_nl(ln))
        fh.write(_nl(seps[3]))

        for ln in out_branches: fh.write(_nl(ln))
        fh.write(_nl(seps[4]))

        for block in out_xfmrs:
            for ln in block:
                fh.write(_nl(ln))
        fh.write(_nl(seps[5]))

        fh.writelines(sections["trailing"])

    if verbose:
        v9_counts = {
            "buses": 100, "loads": 84, "shunts": 13,
            "gens": 54, "branches": 159, "xfmrs": 9,
        }
        print(f"\nWritten: {output_path}")
        print(f"  {'section':<10}  {'produced':>9}  {'v9 expected':>12}")
        print(f"  {'-'*35}")
        for name, produced, section in [
            ("buses",    len(out_buses),    "buses"),
            ("loads",    len(out_loads),    "loads"),
            ("shunts",   len(out_shunts),   "shunts"),
            ("gens",     len(out_gens),     "gens"),
            ("branches", len(out_branches), "branches"),
            ("xfmrs",    len(out_xfmrs),    "xfmrs"),
        ]:
            exp = v9_counts.get(section, "?")
            flag = "" if produced == exp else "  ← check"
            print(f"  {name:<10}  {produced:>9}  {str(exp):>12}{flag}")
        print()


