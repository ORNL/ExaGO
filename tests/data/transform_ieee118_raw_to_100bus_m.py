_SECTION_KEYS = ["bus", "load", "shunt", "gen", "branch", "xfmr"]


def _group_xfmr_blocks(lines: List[str]) -> List[List[str]]:
    blocks: List[List[str]] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        try:
            k_bus = int(line.split(",")[2].strip())
        except (ValueError, IndexError):
            i += 1
            continue
        size = 5 if k_bus != 0 else 4
        blocks.append(lines[i: i + size])
        i += size
    return blocks


def parse_raw_file(filepath: str) -> Tuple[List[str], Dict]:
    with open(filepath, "r") as fh:
        all_lines = fh.readlines()

    header = all_lines[:3]

    sep_indices = [
        i for i, line in enumerate(all_lines)
        if line.strip().startswith("0 /") and "END OF" in line
    ]

    if len(sep_indices) < 6:
        raise ValueError(
            f"Found only {len(sep_indices)} section separators "
            f"(expected ≥ 6). Is '{filepath}' a valid PSS/E RAW v9 file?"
        )

    sep_indices = sep_indices[:6]

    sections: Dict[str, list] = {}
    starts = [3] + [i + 1 for i in sep_indices]
    ends   = sep_indices + [len(all_lines)]

    for key, s, e in zip(_SECTION_KEYS, starts, ends):
        sections[key] = [ln for ln in all_lines[s:e] if ln.strip()]

    sections["separators"]  = [all_lines[i] for i in sep_indices]
    sections["trailing"]    = all_lines[sep_indices[-1] + 1:]
    sections["xfmr_blocks"] = _group_xfmr_blocks(sections["xfmr"])

    return header, sections


def _nl(line):
    return line if line.endswith("\n") else line + "\n"


