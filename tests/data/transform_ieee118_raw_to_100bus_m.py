def main():
    parser = argparse.ArgumentParser(
        description="Transform ieee-118-bus_v1.raw to v9-equivalent and convert to MATPOWER v2 .m."
    )
    parser.add_argument("--input",  default="ieee-118-bus_v1.raw",
                        help="Input v1 RAW file (default: ieee-118-bus_v1.raw)")
    parser.add_argument("--output", default="ieee_118_bus_v10.m",
                        help="Output .m file (default: ieee_118_bus_v10.m)")
    args = parser.parse_args()

    m_path    = Path(args.output)
    func_name = re.sub(r'[^a-zA-Z0-9_]', '_', m_path.stem)

    tmp_fd, tmp_raw = tempfile.mkstemp(suffix='.raw')
    os.close(tmp_fd)
    try:
        transform(args.input, tmp_raw, verbose=False)
        sections = split_sections(tmp_raw)
        baseMVA, bus_df, gen_df, branch_df = build_mpc(sections)
        write_m(m_path, func_name, baseMVA, bus_df, gen_df, branch_df, seed=GENCOST_SEED)
        print(f'Written: {m_path}')
    finally:
        os.unlink(tmp_raw)


if __name__ == "__main__":
    main()
